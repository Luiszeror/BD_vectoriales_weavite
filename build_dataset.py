def main():
    out = Path(__file__).parent / "data"
    out.mkdir(exist_ok=True)

    autores = [
        {"autor_id": f"A{i+1:02d}", "nombre": n, "pais": p, "anio_nacimiento": y, "bio": b}
        for i, (n, p, y, b) in enumerate(AUTORES)
    ]

    libros, resenas = [], []
    for i, (titulo, a, genero, anio, pag, rating, sin, r1, r2) in enumerate(LIBROS):
        libro_id = f"L{i+1:03d}"
        isbn = f"978-958-{random.randint(1000, 9999)}-{random.randint(10, 99)}-{random.randint(0, 9)}"
        libros.append({
            "libro_id": libro_id, "titulo": titulo, "autor_id": autores[a]["autor_id"],
            "autor": autores[a]["nombre"], "genero": genero, "anio": anio,
            "paginas": pag, "rating": rating, "idioma": "es", "isbn": isbn, "sinopsis": sin,
        })
        for j, texto in enumerate((r1, r2), start=1):
            puntaje = max(1, min(5, round(rating + random.choice([-0.6, -0.2, 0, 0.2, 0.4]))))
            resenas.append({
                "resena_id": f"R{len(resenas)+1:04d}", "libro_id": libro_id,
                "usuario": random.choice(["lector_andino", "pagina_a_pagina", "marta_lee",
                                          "el_bibliotecario", "sofi_y_sus_libros", "nocturno77",
                                          "cafe_y_tinta", "dario_lector", "luna_de_papel"]),
                "puntaje": puntaje, "texto": texto,
            })

    consultas = [{"consulta": c, "tipo": t, "esperados": e, "nota": n} for c, t, e, n in CONSULTAS]

    for nombre, datos in [("autores", autores), ("libros", libros),
                          ("resenas", resenas), ("consultas", consultas)]:
        (out / f"{nombre}.json").write_text(json.dumps(datos, ensure_ascii=False, indent=2), encoding="utf-8")
        print(f"{nombre}.json: {len(datos)} registros")


